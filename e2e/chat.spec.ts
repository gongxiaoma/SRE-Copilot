import { test, expect } from '@playwright/test'
test('流事件实时渲染、Markdown、复制、多轮、重新生成与清空', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByRole('textbox', { name: '输入运维问题' }).fill('测试排查')
  await page.getByRole('textbox').press('Enter')
  await expect(page.getByText('正在检查测试数据。', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '停止生成' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '排查结果' })).toBeVisible()
  await expect(page.locator('table')).toBeVisible()
  await expect(page.locator('.markdown img,.markdown script')).toHaveCount(0)
  await page.getByRole('button', { name: '复制代码', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain('kubectl get pods')
  await page.getByRole('button', { name: '重新生成', exact: true }).click()
  await expect(page.getByRole('heading', { name: '排查结果' })).toBeVisible()
  await expect(page.locator('.user-message')).toHaveCount(1)
  await page.getByRole('textbox').fill('继续排查')
  await page.getByRole('textbox').press('Enter')
  await expect(page.locator('.assistant-message').last().getByText('正在检查测试数据。', { exact: true })).toBeVisible()
  await page.locator('.message-scroll').evaluate(el => { el.scrollTop = 0; el.dispatchEvent(new Event('scroll')) })
  await expect(page.getByRole('heading', { name: '排查结果' })).toHaveCount(2)
  expect(await page.locator('.message-scroll').evaluate(el => el.scrollTop)).toBe(0)
  await page.getByRole('button', { name: '回到最新消息' }).click()
  await expect(page.locator('.assistant-message').last().getByRole('heading', { name: '排查结果' })).toBeVisible()
  await expect(page.locator('.user-message')).toHaveCount(2)
  await page.screenshot({ path: 'test-results/chat-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '清空对话', exact: true }).click()
  await page.getByRole('button', { name: '清空', exact: true }).click()
  await expect(page.getByRole('heading', { name: '今天有什么需要排查？' })).toBeVisible()
  expect(errors).toEqual([])
})

test('停止生成、错误重试与会话切换', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('textbox').fill('停止测试')
  await page.getByRole('textbox').press('Enter')
  await page.getByRole('button', { name: '停止生成' }).click()
  await expect(page.getByText('已停止生成，可重新生成本轮回复。')).toBeVisible()
  await expect(page.getByRole('button', { name: '发送消息' })).toBeDisabled()
  await page.getByRole('button', { name: '新建对话' }).click()
  await page.getByRole('textbox').fill('HTTP失败')
  await page.getByRole('textbox').press('Enter')
  await expect(page.getByRole('alert')).toContainText('503')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('503')
  await expect(page.locator('.user-message')).toHaveCount(1)
  await page.getByRole('button', { name: '◷ 停止测试', exact: true }).click()
  await expect(page.getByText('已停止生成，可重新生成本轮回复。')).toBeVisible()
})

test('移动端侧栏、Shift Enter 和中文输入法', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const input = page.getByRole('textbox')
  await input.fill('第一行')
  await input.press('Shift+Enter')
  await input.press('a')
  await expect(input).toHaveValue('第一行\na')
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true })
  await expect(page.locator('.user-message')).toHaveCount(0)
  await page.getByRole('button', { name: '展开或折叠会话栏' }).click()
  await expect(page.getByRole('button', { name: '新建对话' })).toBeVisible()
  await page.getByRole('button', { name: '关闭会话栏', exact: true }).last().click()
  await input.fill('移动端测试')
  await page.getByRole('button', { name: '发送消息' }).click()
  await expect(page.getByRole('heading', { name: '排查结果' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/chat-mobile.png', fullPage: true })
})
